-- Remove TUDO que a demo criou. Rode como ACCOUNTADMIN.
-- =====================================================================
USE ROLE ACCOUNTADMIN;

DROP USER IF EXISTS EMBED_SVC;
DROP USER IF EXISTS EMBED_SVC_JR;
DROP USER IF EXISTS EMBED_SVC_DIR;
DROP NETWORK POLICY IF EXISTS EMBED_NP;

-- Remove os apps, dados e policies (o DROP DATABASE leva tudo junto)
DROP DATABASE IF EXISTS EMBED_DEMO;

REVOKE ALL CALLER PRIVILEGES ON WAREHOUSE EMBED_WH FROM ROLE ACCOUNTADMIN;
ALTER COMPUTE POOL IF EXISTS EMBED_POOL STOP ALL;
DROP COMPUTE POOL IF EXISTS EMBED_POOL;
DROP WAREHOUSE IF EXISTS EMBED_WH;

DROP ROLE IF EXISTS EMBED_MINTER;
DROP ROLE IF EXISTS ANALISTA_JR;
DROP ROLE IF EXISTS DIRETOR;

-- Volta o embedding ao padrao (nenhum dominio liberado)
ALTER ACCOUNT UNSET STREAMLIT_EMBEDDING_CONTROLS;
